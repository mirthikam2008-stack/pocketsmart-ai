"""
Pydantic data models for PocketSmart AI.
Defines schemas for financial inputs, categorized expense structures, and Gemini JSON outputs.
"""
from typing import List, Optional
from pydantic import BaseModel, Field


class ExpenseItem(BaseModel):
    """Represents a single line-item expense or transaction."""
    date: Optional[str] = Field(default=None, description="Date of the transaction (YYYY-MM-DD)")
    category: str = Field(..., description="Expense category e.g. Housing, Food, Transportation")
    description: str = Field(..., description="Details or merchant name of the expense")
    amount: float = Field(..., gt=0, description="Amount spent in the local currency")


class UserFinancialProfile(BaseModel):
    """User input profile containing income, targets, and list of expenses."""
    monthly_income: float = Field(..., gt=0, description="Total net monthly income")
    savings_target: float = Field(..., ge=0, description="Desired monthly savings goal")
    expenses: List[ExpenseItem] = Field(default_factory=list, description="List of individual expenses")


class FiftyThirtyTwentyComparison(BaseModel):
    """Deterministic comparison against the 50/30/20 financial rule."""
    needs_actual: float = Field(..., description="Actual amount spent on Needs")
    needs_pct: float = Field(..., description="Actual percentage of income on Needs")
    needs_target: float = Field(..., description="Target 50% allocation for Needs")
    
    wants_actual: float = Field(..., description="Actual amount spent on Wants")
    wants_pct: float = Field(..., description="Actual percentage of income on Wants")
    wants_target: float = Field(..., description="Target 30% allocation for Wants")
    
    savings_actual: float = Field(..., description="Actual residual savings/debt repayment")
    savings_pct: float = Field(..., description="Actual percentage of income into Savings")
    savings_target: float = Field(..., description="Target 20% allocation for Savings")

    @property
    def target_needs_amount(self) -> float:
        return self.needs_target

    @property
    def target_wants_amount(self) -> float:
        return self.wants_target

    @property
    def target_savings_amount(self) -> float:
        return self.savings_target


class BaselineBudgetMetrics(BaseModel):
    """Deterministic metrics computed from user financial inputs."""
    total_spend: float = Field(..., description="Sum of all expenses")
    monthly_income: float = Field(..., description="Monthly net income")
    target_savings: float = Field(..., description="Target savings set by user")
    actual_savings: float = Field(..., description="Income minus total spend")
    savings_gap: float = Field(..., description="Target savings minus actual savings (positive means under target)")

    @property
    def savings_rate_percent(self) -> float:
        return self.savings_rate_pct

    savings_rate_pct: float = Field(..., description="Percentage of income saved")
    expense_to_income_pct: float = Field(..., description="Percentage of income spent")
    category_breakdown: dict[str, float] = Field(default_factory=dict, description="Total spend per category")
    fifty_thirty_twenty: FiftyThirtyTwentyComparison


