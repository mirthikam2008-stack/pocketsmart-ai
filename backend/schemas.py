class ExtractedDocumentExpense(BaseModel):
    """A single expense item extracted from an image or PDF document."""
    date: Optional[str] = Field(default=None, description="Transaction date in YYYY-MM-DD or None if not found")
    category: str = Field(default="General", description="Standardized category e.g., Food & Dining, Groceries, Housing, Utilities, Transportation, Shopping, Health, Entertainment, Personal Care, Other")
    merchant_or_description: str = Field(..., description="Name of merchant, store, or expense description")
    amount: float = Field(..., gt=0, description="Numerical transaction amount in normalized base currency")
    confidence_score: float = Field(default=1.0, ge=0.0, le=1.0, description="Extraction confidence score from 0.0 to 1.0")


class MultimodalOCRDocumentReport(BaseModel):
    """Structured extraction report from a receipt image or PDF bank statement."""
    document_type: str = Field(..., description="Type of document identified: 'Receipt', 'Bank Statement', 'Invoice', or 'Unknown'")
    detected_currency: str = Field(default="USD", description="Currency symbol or 3-letter code detected on document")
    institution_or_vendor: Optional[str] = Field(default=None, description="Name of bank, store, or issuing merchant")
    document_summary: str = Field(..., description="Short summary of the document extraction findings and quality")
    extracted_expenses: List[ExtractedDocumentExpense] = Field(default_factory=list, description="List of itemized transactions extracted from the document")
    unreadable_warning: Optional[str] = Field(default=None, description="Warning if parts of the document were blurry, cropped, or ambiguous")


