class BudgetLeak(BaseModel):
    """Identified recurring micro-drain or inefficient spend pattern."""
    category: str = Field(..., description="Category where the leak occurs")
    description: str = Field(..., description="Specific pattern or leak identified")
    estimated_monthly_waste: float = Field(..., ge=0, description="Estimated monthly excess or waste")
    severity: str = Field(..., description="Severity level: Low, Medium, or High")


class SpendingAnomaly(BaseModel):
    """Irregular or outlier transactions detected in the dataset."""
    item: str = Field(..., description="Transaction description or merchant")
    amount: float = Field(..., description="Amount of the anomalous expense")
    reason: str = Field(..., description="Why this is considered an anomaly")


class Recommendation(BaseModel):
    """Actionable advice prioritized by financial impact."""
    priority: int = Field(..., ge=1, le=5, description="Priority rank (1 being most critical)")
    title: str = Field(..., description="Punchy recommendation headline")
    action_plan: str = Field(..., description="Concrete steps the user should take")
    potential_monthly_savings: float = Field(..., ge=0, description="Estimated monthly savings achieved")
    difficulty: str = Field(..., description="Effort level: Easy, Moderate, Challenging")


class AIAnalysisReport(BaseModel):
    """Complete structured response generated by Gemini 3.7 Pro."""
    overall_health_score: int = Field(..., ge=0, le=100, description="Overall financial wellness score from 0 to 100")
    health_summary: str = Field(..., description="Executive summary of user's financial posture")
    budget_leaks: List[BudgetLeak] = Field(default_factory=list, description="Detected financial leaks")
    spending_anomalies: List[SpendingAnomaly] = Field(default_factory=list, description="Detected spending anomalies")
    recommendations: List[Recommendation] = Field(default_factory=list, description="Prioritized recommendations")
    savings_feasibility: str = Field(..., description="Assessment of whether the target savings goal is achievable")


