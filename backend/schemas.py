class FinancialMilestoneGoal(BaseModel):
    """Target financial milestone parameters configured by the user."""
    goal_type: str = Field(default="Emergency Fund", description="Goal type: 'Emergency Fund', 'Debt Paydown (Snowball/Avalanche)', 'Home Down Payment', or 'Major Purchase'")
    target_amount: float = Field(..., gt=0, description="Target savings or debt balance amount in dollars")
    target_timeline_months: int = Field(default=12, ge=1, le=60, description="Desired timeline in months to achieve the goal")
    current_savings_or_debt: float = Field(default=0.0, ge=0, description="Current starting balance or outstanding debt")

    def __init__(self, **data):
        if "goal_name" in data and "goal_type" not in data:
            data["goal_type"] = data.pop("goal_name")
        if "timeline_months" in data and "target_timeline_months" not in data:
            data["target_timeline_months"] = data.pop("timeline_months")
        if "current_starting_balance" in data and "current_savings_or_debt" not in data:
            data["current_savings_or_debt"] = data.pop("current_starting_balance")
        super().__init__(**data)

    @property
    def goal_name(self) -> str:
        return self.goal_type


class CategoryCutPlan(BaseModel):
    """Granular budget reduction item proposed by the autonomous strategist."""
    category: str = Field(..., description="Target expense category for reduction")
    current_spend: float = Field(..., ge=0, description="Current monthly spend in this category")
    proposed_spend: float = Field(..., ge=0, description="Proposed target spend in this category")
    monthly_cut_amount: float = Field(..., ge=0, description="Amount saved each month by implementing this cut")
    rationale_and_tradeoffs: str = Field(..., description="Contextual rationale and lifestyle trade-offs")


class ScenarioTrajectory(BaseModel):
    """Deterministic month-by-month financial projection for a single scenario."""
    scenario_name: str = Field(..., description="Name of scenario: 'Status Quo Runway', 'Balanced Lifestyle', or 'Aggressive Austerity'")
    monthly_burn_rate: float = Field(..., description="Projected total monthly spend under this scenario")
    monthly_savings_accumulation: float = Field(..., description="Net monthly savings added toward the goal")
    months_to_goal: int = Field(..., description="Projected months required to achieve target amount")
    goal_achieved_within_target: bool = Field(..., description="Whether the milestone is met within the user's timeline")
    monthly_cumulative_balances: List[float] = Field(default_factory=list, description="Projected cumulative balance for each month (e.g. months 1 to N)")
    risk_level: str = Field(..., description="Risk or burnout difficulty: 'Low', 'Moderate', 'High'")

    @property
    def cumulative_balance_curve(self) -> List[float]:
        return self.monthly_cumulative_balances



class AutonomousSimulationReport(BaseModel):
    """Complete multi-scenario optimization report generated by Gemini 3.7 Pro."""
    milestone_summary: str = Field(..., description="Executive summary of the milestone goal feasibility")
    recommended_scenario: str = Field(..., description="Best recommended scenario for this specific user profile")
    status_quo_scenario: ScenarioTrajectory
    balanced_scenario: ScenarioTrajectory
    aggressive_scenario: ScenarioTrajectory
    category_cut_schedule: List[CategoryCutPlan] = Field(default_factory=list, description="Actionable category reduction schedule for the recommended plan")
    strategic_advice: str = Field(..., description="High-level financial quantitative strategy and behavioral sustainability advice")


